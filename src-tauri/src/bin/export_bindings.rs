//! On-demand `tauri-specta` bindings export.
//!
//! Run with:
//!
//!     cargo run --bin export_bindings --manifest-path src-tauri/Cargo.toml
//!
//! Writes `client/src/lib/bindings.ts` from the live command set defined in
//! `protopulse::specta_builder()`. Commit the resulting diff. The same export
//! also runs automatically on every debug `tauri::Builder` startup via the
//! `cfg(debug_assertions)` block in `lib.rs::run()`, but this standalone
//! binary lets us regenerate bindings without booting the full app — useful
//! in CI, pre-commit hooks, and one-off command-set changes.

use specta_typescript::Typescript;
use std::path::PathBuf;

fn main() {
    let builder = protopulse::specta_builder();

    // Compute the output path from CARGO_MANIFEST_DIR (src-tauri/), independent
    // of the caller's working directory. This means `cargo run --bin
    // export_bindings` works whether invoked from the repo root, src-tauri/,
    // or anywhere else.
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let output = manifest_dir
        .parent()
        .expect("src-tauri/ has a parent (repo root)")
        .join("client")
        .join("src")
        .join("lib")
        .join("bindings.ts");

    let typescript = Typescript::default()
        .header("/* eslint-disable */\n// Generated by tauri-specta — do not edit.\n");

    match builder.export(typescript, &output) {
        Ok(_) => {
            println!("[export_bindings] Wrote {}", output.display());
        }
        Err(e) => {
            eprintln!(
                "[export_bindings] Failed to export {}: {}",
                output.display(),
                e
            );
            std::process::exit(1);
        }
    }
}
