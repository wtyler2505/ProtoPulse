export interface Stroke {
  a: Vec;
  b: Vec;
}

/**
 * Render `text` as stroke segments, left-to-right from `origin`, in
 * integer nanometers. Unknown characters (anything outside A-Z/0-9,
 * case-folded) are skipped — they still advance the cursor so spacing
 * stays consistent, matching the legacy renderer's behavior.
 */
export function textToStrokes(
  text: string,
  origin: Vec,
  charWNm: number,
  charHNm: number,
  spacingNm: number,
): Stroke[] {
  const strokes: Stroke[] = [];
  let cursorX = origin.x;
  for (const raw of text) {
    const glyph = STROKE_FONT[raw.toUpperCase()];
    if (glyph) {
      for (const [nx1, ny1, nx2, ny2] of glyph) {
        strokes.push({
          a: { x: Math.round(cursorX + nx1 * charWNm), y: Math.round(origin.y + ny1 * charHNm) },
          b: { x: Math.round(cursorX + nx2 * charWNm), y: Math.round(origin.y + ny2 * charHNm) },
        });
      }
    }
    cursorX += charWNm + spacingNm;
  }
  return strokes;
}
